score = 1

if 90 <= score <= 100:
    print(f"Score: {score}\nGrade: A")
    
elif 80 <= score <= 89:
    print(f"Score: {score}\nGrade: B")

elif 70 <= score <= 79:
    print(f"Score: {score}\nGrade: C")

elif 60 <= score <= 69:
    print(f"Score: {score}\nGrade: D")
    
else:
    print(f"Score: {score}\nGrade: F")